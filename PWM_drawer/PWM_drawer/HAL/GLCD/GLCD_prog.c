static void GLCD_voidChipSelect(u8 copy_u8side) {
	switch (copy_u8side) {
		case GLCD_RIGHT_SIDE:
		DIO_voidSetPinVal(GLCD_CPORT, GLCD_CCS1, HIGH);
		DIO_voidSetPinVal(GLCD_CPORT, GLCD_CCS2, LOW);
		GLCD_CURRENTX = 64;
		break;
		case GLCD_LEFT_SIDE:
		DIO_voidSetPinVal(GLCD_CPORT, GLCD_CCS1, LOW);
		DIO_voidSetPinVal(GLCD_CPORT, GLCD_CCS2, HIGH);
		GLCD_CURRENTX = 0;
		break;
		case GLCD_BOTH_SIDES:
		DIO_voidSetPinVal(GLCD_CPORT, GLCD_CCS1, HIGH);
		DIO_voidSetPinVal(GLCD_CPORT, GLCD_CCS2, HIGH);
		break;
	}
}


static void GLCD_voidEnPulse(void) {
	DIO_voidSetPinVal(GLCD_CPORT, GLCD_E, HIGH);       // set E
	DIO_voidSetPinVal(GLCD_CPORT, GLCD_E, LOW);        // clear E
}


void GLCD_voidInit(void) {
	/* set pin directions */
	DIO_voidSetPortDir(GLCD_DPORT, OUTPUT);

	DIO_voidSetPinDir(GLCD_CPORT, GLCD_CCS1, OUTPUT);
	DIO_voidSetPinDir(GLCD_CPORT, GLCD_CCS2, OUTPUT);
	DIO_voidSetPinDir(GLCD_CPORT, GLCD_RS,   OUTPUT);
	DIO_voidSetPinDir(GLCD_CPORT, GLCD_RW,   OUTPUT);
	DIO_voidSetPinDir(GLCD_CPORT, GLCD_E,    OUTPUT);
	DIO_voidSetPinDir(GLCD_CPORT, GLCD_RST,  OUTPUT);

	/* reset the GLCD */
	DIO_voidSetPinVal(GLCD_CPORT, GLCD_RST, LOW);
	DIO_voidSetPinVal(GLCD_CPORT, GLCD_RST, HIGH);

	GLCD_voidClearDisplay();
	GLCD_voidSendCommand(0x40, GLCD_RIGHT_SIDE);
	GLCD_voidSendCommand(0x40, GLCD_LEFT_SIDE);
	GLCD_voidSendCommand(0x3F, GLCD_RIGHT_SIDE);
	GLCD_voidSendCommand(0x3F, GLCD_LEFT_SIDE);
	GLCD_voidSendCommand(0xB8, GLCD_RIGHT_SIDE);
	GLCD_voidSendCommand(0xB8, GLCD_LEFT_SIDE);
	GLCD_CURRENTX = 0;
	GLCD_CURRENTY = 0;
}


void GLCD_voidSendCommand(u8 copy_u8command, u8 copy_u8side) {
	DIO_voidSetPinVal(GLCD_CPORT, GLCD_RS, LOW);       // command mode
	DIO_voidSetPinVal(GLCD_CPORT, GLCD_RW, LOW);       // write mode
	
	/* send command */
	GLCD_voidChipSelect(copy_u8side);
	DIO_voidSetPortVal(GLCD_DPORT, copy_u8command);
	GLCD_voidEnPulse();
}


void GLCD_voidSendData(u8 copy_u8data) {
	if (GLCD_CURRENTX > 128 || GLCD_CURRENTY > 8) return;
	
	if (GLCD_CURRENTX == 64) {
		GLCD_voidChipSelect(GLCD_RIGHT_SIDE);
		GLCD_voidSendCommand(0xB8 | GLCD_CURRENTY, GLCD_RIGHT_SIDE);
		GLCD_voidSendCommand(0x40, GLCD_RIGHT_SIDE);
	} else if (GLCD_CURRENTX == 128) {
		GLCD_CURRENTX = 0;
		GLCD_CURRENTY++;
		if (GLCD_CURRENTY == 8) GLCD_CURRENTY = 0;
		GLCD_voidSendCommand(0xB8 | GLCD_CURRENTY, GLCD_RIGHT_SIDE);
		GLCD_voidSendCommand(0x40, GLCD_RIGHT_SIDE);
		GLCD_voidSendCommand(0xB8 | GLCD_CURRENTY, GLCD_LEFT_SIDE);
		GLCD_voidSendCommand(0x40, GLCD_LEFT_SIDE);
	}
	
	DIO_voidSetPinVal(GLCD_CPORT, GLCD_RS, HIGH);      // data mode
	DIO_voidSetPinVal(GLCD_CPORT, GLCD_RW, LOW);       // send mode
	
	/* send data */
	DIO_voidSetPortVal(GLCD_DPORT, copy_u8data);
	GLCD_voidEnPulse();
	GLCD_CURRENTX++;
}


void GLCD_voidClearDisplay(void) {
	for (u16 i = 0; i < 1024; i++) GLCD_voidSendData(0x00);
}


void GLCD_voidGotoXY(u8 copy_u8x, u8 copy_u8y) {
	if (copy_u8x < 64) {
		GLCD_voidSendCommand(0xB8 | copy_u8y, GLCD_LEFT_SIDE);
		GLCD_voidSendCommand(0x40 | copy_u8x, GLCD_LEFT_SIDE);
	} else {
		GLCD_voidSendCommand(0xB8 | copy_u8y, GLCD_RIGHT_SIDE);
		GLCD_voidSendCommand(0x40 | (copy_u8x - 64), GLCD_RIGHT_SIDE);
	}
	
	GLCD_CURRENTX = copy_u8x;
	GLCD_CURRENTY = copy_u8y;
}


void GLCD_voidSendString(const s8* string) {
	u8 i = 0;
	
	while (string[i]) {
		GLCD_voidDrawChar(string[i]);
		i++;
	}
}


void GLCD_voidDrawChar(u8 copy_u8char) {
	u8 index = copy_u8char - 32;
	
	for (u8 i = 0; i < 6; i++) GLCD_voidSendData(GLCD_CHARS[index][i]);
}


void GLCD_voidSendNum(u32 num) {
	u8 data[10] = {0};
	u8 i = 0;
	
	do
	{
		data[i] = num % 10;
		i++;
		num /= 10;
	} while (num != 0);
	
	for (u8 j = 0; j < i; j++) GLCD_voidDrawChar(data[i - j - 1] + '0');
}


void GLCD_voidDrawPattern(const u8* pattern, u8 copy_u8size) {
	u8 i = 0;
	
	while (i < copy_u8size) {
		GLCD_voidSendData(pattern[i]);
		i++;
	}
}
